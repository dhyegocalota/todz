import { Language } from '@todz/types';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import type { GeneratedEmail } from '../../src/emails/generated-email';
import { ADMIN_SIGN_IN_EMAIL_COPY_BY_LANGUAGE } from './admin-sign-in-email-copy';
import { generatedAdminSignInEmail } from './admin-sign-in-template';
import { DAY_EMAIL_COPY_BY_LANGUAGE, DAY_EMAIL_EMPTY_COPY_BY_LANGUAGE } from './day-email-copy';
import { generatedDayEmailEmpty, generatedDayEmailWithTasks } from './day-email-template';
import { OAUTH_SIGN_IN_EMAIL_COPY_BY_LANGUAGE } from './oauth-sign-in-email-copy';
import { generatedOAuthSignInEmail } from './oauth-sign-in-template';
import { SIGN_IN_EMAIL_COPY_BY_LANGUAGE } from './sign-in-email-copy';
import { generatedSignInEmail } from './sign-in-template';
import { WELCOME_EMAIL_COPY_BY_LANGUAGE } from './welcome-email-copy';
import { generatedWelcomeEmail } from './welcome-template';

export const GENERATED_EMAILS_PATH = fileURLToPath(new URL('../../src/emails/generated/email-templates.ts', import.meta.url));

export enum EmailTemplateName {
  SignIn = 'sign-in',
  Welcome = 'welcome',
  AdminSignIn = 'admin-sign-in',
  DayEmail = 'day-email',
  DayEmailEmpty = 'day-email-empty',
  OAuthSignIn = 'oauth-sign-in',
}

export type GeneratedEmailsByLanguage = Record<Language, GeneratedEmail>;

const HEADER = '// NB ADR 0042: generated by pnpm emails:generate; never edit by hand';
const IMPORTS = ["import { Language } from '@todz/types';", "import type { GeneratedEmail } from '../generated-email';"].join('\n');
const EXPORT_NAMES: Record<EmailTemplateName, string> = {
  [EmailTemplateName.SignIn]: 'SIGN_IN_EMAIL',
  [EmailTemplateName.Welcome]: 'WELCOME_EMAIL',
  [EmailTemplateName.AdminSignIn]: 'ADMIN_SIGN_IN_EMAIL',
  [EmailTemplateName.DayEmail]: 'DAY_EMAIL',
  [EmailTemplateName.DayEmailEmpty]: 'DAY_EMAIL_EMPTY',
  [EmailTemplateName.OAuthSignIn]: 'OAUTH_SIGN_IN_EMAIL',
};

async function generatedInEveryLanguage(generate: (language: Language) => Promise<GeneratedEmail>): Promise<GeneratedEmailsByLanguage> {
  const entries = await Promise.all(Object.values(Language).map(async (language) => [language, await generate(language)] as const));
  return Object.fromEntries(entries) as GeneratedEmailsByLanguage;
}

export async function generatedEmailsOf(): Promise<Record<EmailTemplateName, GeneratedEmailsByLanguage>> {
  return {
    [EmailTemplateName.SignIn]: await generatedInEveryLanguage((language) =>
      generatedSignInEmail({ copy: SIGN_IN_EMAIL_COPY_BY_LANGUAGE[language], language }),
    ),
    [EmailTemplateName.Welcome]: await generatedInEveryLanguage((language) =>
      generatedWelcomeEmail({ copy: WELCOME_EMAIL_COPY_BY_LANGUAGE[language], language }),
    ),
    [EmailTemplateName.AdminSignIn]: await generatedInEveryLanguage((language) =>
      generatedAdminSignInEmail({ copy: ADMIN_SIGN_IN_EMAIL_COPY_BY_LANGUAGE[language], language }),
    ),
    [EmailTemplateName.DayEmail]: await generatedInEveryLanguage((language) =>
      generatedDayEmailWithTasks({ copy: DAY_EMAIL_COPY_BY_LANGUAGE[language], language }),
    ),
    [EmailTemplateName.DayEmailEmpty]: await generatedInEveryLanguage((language) =>
      generatedDayEmailEmpty({ copy: DAY_EMAIL_EMPTY_COPY_BY_LANGUAGE[language], language }),
    ),
    [EmailTemplateName.OAuthSignIn]: await generatedInEveryLanguage((language) =>
      generatedOAuthSignInEmail({ copy: OAUTH_SIGN_IN_EMAIL_COPY_BY_LANGUAGE[language], language }),
    ),
  };
}

function declarationOf({ name, emails }: { name: EmailTemplateName; emails: GeneratedEmailsByLanguage }): string {
  const entries = Object.entries(Language).map(([key, language]) => `[Language.${key}]: ${JSON.stringify(emails[language], null, 2)}`);
  return `export const ${EXPORT_NAMES[name]}: Record<Language, GeneratedEmail> = {\n${entries.join(',\n')}\n};`;
}

export async function generatedEmailsSource(): Promise<string> {
  const emails = await generatedEmailsOf();
  const declarations = Object.values(EmailTemplateName).map((name) => declarationOf({ name, emails: emails[name] }));
  const source = [HEADER, IMPORTS, ...declarations].join('\n\n');
  const options = await resolveConfig(GENERATED_EMAILS_PATH);
  if (options === null) throw new Error(`no Prettier configuration found for ${GENERATED_EMAILS_PATH}`);
  return format(source, { ...options, filepath: GENERATED_EMAILS_PATH });
}
