import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { markdownHtml } from './markdown-html';

export const GENERATED_SITE_PATH = fileURLToPath(new URL('../../src/site/generated/self-host-html.ts', import.meta.url));
const GUIDE_PATH = fileURLToPath(new URL('../../../../docs/self-host.md', import.meta.url));
const HEADER = '// NB ADR 0048: generated by pnpm site:generate from docs/self-host.md; never edit by hand';

export async function generatedSiteSource(): Promise<string> {
  const html = markdownHtml(readFileSync(GUIDE_PATH, 'utf8'));
  const source = [HEADER, `export const SELF_HOST_HTML: string = ${JSON.stringify(html)};`].join('\n\n');
  const options = await resolveConfig(GENERATED_SITE_PATH);
  if (options === null) throw new Error(`no Prettier configuration found for ${GENERATED_SITE_PATH}`);
  return format(source, { ...options, filepath: GENERATED_SITE_PATH });
}
